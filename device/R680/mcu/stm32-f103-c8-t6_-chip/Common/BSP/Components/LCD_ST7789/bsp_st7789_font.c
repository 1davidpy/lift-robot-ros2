static const uint8_t *font5x7_glyph(char ch)
{
    if (ch >= 'a' && ch <= 'z')
    {
        ch = (char)(ch - 'a' + 'A');
    }

    if (ch < FONT5X7_FIRST_CHAR || ch > FONT5X7_LAST_CHAR)
    {
        ch = ' ';
    }

    return font5x7_table[(uint8_t)(ch - FONT5X7_FIRST_CHAR)];
}

uint16_t BSP_ST7789_TextWidth5x7(const char *text, uint8_t scale)
{
    uint16_t width = 0U;

    if (text == 0 || scale == 0U)
    {
        return 0U;
    }

    while (*text != '\0')
    {
        width = (uint16_t)(width + ((BSP_ST7789_FONT5X7_WIDTH + BSP_ST7789_FONT5X7_SPACING) * scale));
        text++;
    }

    return width;
}

void BSP_ST7789_DrawChar5x7(int16_t x, int16_t y, char ch, uint16_t color, uint8_t scale)
{
    const uint8_t *glyph = font5x7_glyph(ch);

    if (scale == 0U)
    {
        return;
    }

    for (uint8_t col = 0U; col < BSP_ST7789_FONT5X7_WIDTH; col++)
    {
        for (uint8_t row = 0U; row < BSP_ST7789_FONT5X7_HEIGHT; row++)
        {
            if ((glyph[col] & (1U << row)) == 0U)
            {
                continue;
            }

            for (uint8_t sx = 0U; sx < scale; sx++)
            {
                const int16_t px = (int16_t)(x + (int16_t)(col * scale) + sx);
                const int16_t py = (int16_t)(y + (int16_t)(row * scale));

                if (px >= 0 && py >= 0 &&
                    px < (int16_t)BSP_ST7789_GetWidth() &&
                    py < (int16_t)BSP_ST7789_GetHeight())
                {
                    uint16_t y1 = (uint16_t)(py + scale - 1U);

                    if (y1 >= BSP_ST7789_GetHeight())
                    {
                        y1 = (uint16_t)(BSP_ST7789_GetHeight() - 1U);
                    }

                    BSP_ST7789_Fill((uint16_t)px,
                                    (uint16_t)py,
                                    (uint16_t)px,
                                    y1,
                                    color);
                }
            }
        }
    }
}

void BSP_ST7789_DrawString5x7(int16_t x, int16_t y, const char *text, uint16_t color, uint8_t scale)
{
    if (text == 0 || scale == 0U)
    {
        return;
    }

    while (*text != '\0')
    {
        BSP_ST7789_DrawChar5x7(x, y, *text, color, scale);
        x = (int16_t)(x + (int16_t)((BSP_ST7789_FONT5X7_WIDTH + BSP_ST7789_FONT5X7_SPACING) * scale));
        text++;
    }
}
